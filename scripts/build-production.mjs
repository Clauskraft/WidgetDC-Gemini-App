import { spawn, execSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFileSync } from "node:fs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const viteBin = resolve(root, "node_modules", "vite", "bin", "vite.js");

// Deploy-parity: bake the ACTUAL commit being built into the bundle so /health
// reports the served-artifact SHA — not the deploy-env SHA, which a Railway
// "Redeploy" can advance while re-serving a stale image (build ≠ env exposes it).
function resolveBuildSha() {
  const fromEnv =
    process.env.RAILWAY_GIT_COMMIT_SHA ??
    process.env.VERCEL_GIT_COMMIT_SHA ??
    process.env.COMMIT_SHA ??
    process.env.GITHUB_SHA;
  if (fromEnv && fromEnv.trim()) return fromEnv.trim();
  try {
    return execSync("git rev-parse HEAD", { cwd: root }).toString().trim();
  } catch {
    return "unknown";
  }
}

const buildSha = resolveBuildSha();
const builtAt = new Date().toISOString();
writeFileSync(
  resolve(root, "src", "lib", "build-info.ts"),
  `/**\n * Build-time artifact identity — GENERATED by scripts/build-production.mjs.\n * Baked into the served bundle so /health reports the served-artifact SHA.\n */\nexport const BUILD_SHA = ${JSON.stringify(buildSha)};\nexport const BUILT_AT = ${JSON.stringify(builtAt)};\n`,
);
console.log(`[build] baked BUILD_SHA=${buildSha} (built_at=${builtAt})`);

const child = spawn(process.execPath, [viteBin, "build", "--mode", "production"], {
  cwd: root,
  env: { ...process.env, NODE_ENV: "production" },
  stdio: "inherit",
});

child.on("exit", (code, signal) => {
  if (signal) process.kill(process.pid, signal);
  process.exit(code ?? 1);
});
